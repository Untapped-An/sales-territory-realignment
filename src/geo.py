CITY_TO_REGION = {
    c.replace("_", " "): region
    for region, block in _REGION_CITIES.items()
    for c in block.split()
}


def clean_city(city: str) -> str:
    c = " ".join(str(city).upper().split())
    return SPELLING_FIXES.get(c, c)


def region_of(city: str) -> str:
    return CITY_TO_REGION.get(clean_city(city), "UNMAPPED")
